public class BangKieuDuLieu {
    public static void main(String[] args) {
        System.out.println("byte    " + Byte.BYTES + " byte   từ " + Byte.MIN_VALUE + " đến " + Byte.MAX_VALUE);
        System.out.println("short   " + Short.BYTES + " byte   từ " + Short.MIN_VALUE + " đến " + Short.MAX_VALUE);
        System.out.println("int     " + Integer.BYTES + " byte   từ " + Integer.MIN_VALUE + " đến " + Integer.MAX_VALUE);
        System.out.println("long    " + Long.BYTES + " byte   từ " + Long.MIN_VALUE + " đến " + Long.MAX_VALUE);
        System.out.println("float   " + Float.BYTES + " byte   tối đa khoảng " + Float.MAX_VALUE);
        System.out.println("double  " + Double.BYTES + " byte   tối đa khoảng " + Double.MAX_VALUE);
        System.out.println("char    " + Character.BYTES + " byte   một ký tự Unicode, ví dụ 'ộ'");
        System.out.println("boolean chỉ có true hoặc false");
    }
}
